"""Prepare a small, offline Australian state map from Natural Earth Admin-1 GeoJSON.

Usage: python3 scripts/prepare-reach-map.py /path/to/ne_50m_admin_1_states_provinces.geojson
Source: https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_50m_admin_1_states_provinces.geojson
Licence: public domain, https://www.naturalearthdata.com/about/terms-of-use/
"""
import hashlib
import json
import math
import sys
from pathlib import Path

source = Path(sys.argv[1])
features = [f for f in json.loads(source.read_text())["features"] if f["properties"].get("admin") == "Australia"]

# Spherical Australian Albers equal-area projection, standard parallels 18S / 36S.
phi1, phi2 = math.radians(-18), math.radians(-36)
n = (math.sin(phi1) + math.sin(phi2)) / 2
c = math.cos(phi1) ** 2 + 2 * n * math.sin(phi1)
rho0 = math.sqrt(c) / n

def project(point):
    lon, lat = point[:2]
    rho = math.sqrt(c - 2 * n * math.sin(math.radians(lat))) / n
    theta = n * math.radians(lon - 132)
    return rho * math.sin(theta), rho0 - rho * math.cos(theta)

def polygons(feature):
    geo = feature["geometry"]
    parts = geo["coordinates"] if geo["type"] == "MultiPolygon" else [geo["coordinates"]]
    # Mainland and Tasmania, including coastal islands; omit remote island territories.
    return [part for part in parts if all(111 < lon < 155 and -45 < lat < -9 for lon, lat, *_ in part[0])]

points = [project(p) for f in features for part in polygons(f) for ring in part for p in ring]
min_x, max_x = min(p[0] for p in points), max(p[0] for p in points)
min_y, max_y = min(p[1] for p in points), max(p[1] for p in points)
width, height, pad = 820, 720, 44
scale = min((width - 2 * pad) / (max_x - min_x), (height - 2 * pad) / (max_y - min_y))
offset_x = (width - (max_x - min_x) * scale) / 2
offset_y = (height - (max_y - min_y) * scale) / 2

def screen(point):
    x, y = project(point)
    return (offset_x + (x - min_x) * scale, offset_y + (max_y - y) * scale)

def simplify(points, tolerance=.4):
    if len(points) <= 2:
        return points
    a, b = points[0], points[-1]
    dx, dy = b[0] - a[0], b[1] - a[1]
    def distance(p):
        if dx == dy == 0:
            return math.hypot(p[0] - a[0], p[1] - a[1])
        t = max(0, min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / (dx * dx + dy * dy)))
        return math.hypot(p[0] - a[0] - t * dx, p[1] - a[1] - t * dy)
    distances = [distance(p) for p in points[1:-1]]
    largest = max(distances, default=0)
    if largest <= tolerance:
        return [a, b]
    index = distances.index(largest) + 1
    return simplify(points[:index + 1], tolerance)[:-1] + simplify(points[index:], tolerance)

states = []
for feature in features:
    prop = feature["properties"]
    code = prop["iso_3166_2"].removeprefix("AU-")
    if code == "X02~":
        code = "JBT"
    paths = []
    for part in polygons(feature):
        for ring in part:
            reduced = simplify([screen(p) for p in ring])
            if len(reduced) >= 4:
                paths.append("M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in reduced) + "Z")
    x, y = screen((prop["longitude"], prop["latitude"]))
    states.append({"code": code, "name": prop["name"], "path": "".join(paths), "x": round(x, 1), "y": round(y, 1)})

assert {"VIC", "QLD", "NSW", "SA", "WA", "TAS", "NT", "ACT"} <= {s["code"] for s in states}
assert next(s for s in states if s["code"] == "TAS")["y"] > next(s for s in states if s["code"] == "VIC")["y"]
result = {"width": width, "height": height, "states": states}
target = Path(__file__).resolve().parents[1] / "reach-map.mjs"
target.write_text("// Natural Earth Admin-1, public domain. Generated by scripts/prepare-reach-map.py.\n"
                  "// Source SHA-256: " + hashlib.sha256(source.read_bytes()).hexdigest() + "\n"
                  "// https://www.naturalearthdata.com/about/terms-of-use/\n"
                  "export const reachMap=" + json.dumps(result, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(f"Prepared {len(states)} state/territory shapes, including Tasmania: {target.stat().st_size:,} bytes")
for state in states:
    print(state["code"], state["x"], state["y"])
